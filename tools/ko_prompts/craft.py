STYLE_GUIDE = """한국 웹소설 문체 기준 (반드시 지킨다):
[문단과 문장]
- 문단은 대부분 한 문장, 길어도 두세 문장이다. 한 문단이 모바일 화면 세 줄(약 80자)을 넘기지 않게 끊는다. 한 회차는 짧은 문단 150~220개로 이루어진다.
- 반전, 깨달음, 강조, 웃음 포인트는 한 줄짜리 문단으로 따로 떼어 호흡을 끊는다. (‘아.’ / 망했다. / 그런데 문제가 있었다.)
- 서술은 과거형(~했다, ~였다)으로 일관한다. 현재형은 속마음과 대사에만.
- 문장은 짧고 단단하게. 수식어를 겹겹이 쌓지 않고, 관형절을 두 개 이상 겹치지 않는다.
- 가끔 인물로 문장을 맺어 여운을 준다(‘…미소를 짓는 수밖에 없는 나였다.’). 남발하지 않는다.
[비트]
- 행동 → 반응 → 속마음 → 대사가 몇 문단 단위로 빠르게 돈다. 서술만 다섯 문단 넘게 이어지지 않는다.
- 속마음은 작은따옴표 한 줄로: ‘이게 된다고?’ 주인공의 속마음은 솔직하고 구어적이며 자조와 태클이 섞인다. 독자가 주인공과 같이 웃고 긴장하게 만드는 통로다.
- ‘~라고 말했다’ 같은 대사 태그를 반복하지 않는다. 대사 앞뒤의 짧은 행동 비트나 호칭으로 화자를 드러낸다.
- 대사는 입말이다. 인물마다 어미·말버릇·호칭이 다르다. 한 번에 서너 문장 넘는 연설을 시키지 않는다.
- 시스템 메시지와 상태창은 대괄호로 한 줄에 하나씩: [스킬 ‘검술 기초’를 획득했습니다.]
- 효과음은 아껴서 단독 줄로: 쾅! / -콰직!
- 말끝을 흐리거나 끊을 때는 ‘……’와 ‘-’를 쓴다.
[설명]
- 세계관 설명은 주인공이 아는 것(원작 지식, 경험)을 속마음으로 짧게 떠올리거나 대사로 흘린다. 설명 문단은 세 문장 이하, 연달아 두 번 넘게 두지 않는다.
- 독자가 이미 아는 것을 다시 설명하지 않는다. 앞 회차 내용을 요약하지 않는다.
[감정과 묘사]
- 감정은 이름 붙이기보다 행동·반응·속마음으로 보여 준다. 다만 웹소설답게 속마음으로는 직설적으로 말해도 된다(‘솔직히 무서웠다.’).
- 묘사는 장면에 필요한 구체적인 디테일 한두 개로 끝낸다. 풍경·빛·색을 한 문단 넘게 묘사하지 않는다.
[금지 — 서구 소설식·AI식 문장]
- 은유와 직유의 연발(‘마치 ~처럼’은 한 장면에 한 번 이하), ‘~의 무게’, ‘형언할 수 없는’, ‘운명의 수레바퀴’, ‘공기가 무거워졌다’, ‘시간이 멈춘 듯했다’, ‘침묵이 내려앉았다’, ‘심연’, ‘폭풍전야’ 같은 상투구.
- 문장을 ‘그는/그녀는’으로 계속 시작하기. 한국어는 주어를 생략하거나 이름·호칭을 쓴다.
- 번역투: ‘~하는 것이었다’ 반복, ‘~하고 있었다’ 남발, ‘~에 대해’, ‘~를 통해’, ‘~에 있어서’, ‘~를 가지고 있다’, 이중 피동(‘되어지다’).
- 장면이나 회차 끝의 감상적 요약·교훈·내레이터 예고(‘앞으로 무슨 일이 기다리고 있을지 아무도 몰랐다’).
- 인물이 자기 감정을 긴 문장으로 분석하는 독백, 서양 고전 소설 같은 격식체 대사(‘오, 신이시여’, ‘나의 레이디’)."""

